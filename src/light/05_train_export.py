#!/usr/bin/env python3
"""
Step 5 - Train the deployable models on all clean events and export them.

  server/models/light_rf_{dusk,dawn}.joblib   - weather-conditioned RF (server tier)
  firmware/light_node_hybrid/seasonal_model.h - on-chip seasonal clock (offline tier)

Safety margins come from the equal-safety analysis (Step 3): the shift that keeps
the out-of-fold violation rate (unlit > 5 min) at or below TARGET_VIOLATION.
"""
import sys, json, warnings
from pathlib import Path
import numpy as np, pandas as pd, joblib
from sklearn.linear_model import Ridge
from sklearn.ensemble import RandomForestRegressor
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import *  # noqa
warnings.filterwarnings("ignore")

TARGET_VIOLATION = 0.10
WF = [v + "_w" for v in WEATHER_VARS]
ev = pd.read_csv(PROC / "light_events.csv", parse_dates=["date"])
C = pd.read_csv(TAB / "light_pareto_curves.csv")
MODEL_DIR = ROOT / "server" / "models"; MODEL_DIR.mkdir(parents=True, exist_ok=True)

def margin(kind, policy):
    c = C[(C.event == kind) & (C.policy == policy) & (C.viol_rate <= TARGET_VIOLATION)]
    return float(c.sort_values("waste_min").knob.iloc[0])

meta, hdr = {}, []
for kind in ["dusk", "dawn"]:
    s = ev[ev.kind == kind]
    y = s.offset_min.values
    rf = RandomForestRegressor(n_estimators=500, min_samples_leaf=4, max_features=0.4,
                               random_state=SEED, n_jobs=-1).fit(s[ASTRO + WF].fillna(s[WF].median()), y)
    joblib.dump(rf, MODEL_DIR / f"light_rf_{kind}.joblib", compress=3)
    sea = Ridge(alpha=1.0).fit(s[ASTRO].values, y)
    lo, hi = np.percentile(y, [5, 95])
    m_rf, m_sea = margin(kind, "RF virtual photocell"), margin(kind, "Seasonal clock")
    meta[kind] = dict(rf_margin_min=m_rf, seasonal_margin_min=m_sea, clamp_lo=lo, clamp_hi=hi,
                      weather_medians=s[WF].median().to_dict(), n_train=len(s),
                      train_months=sorted(s.month.unique().tolist()))
    K = kind.upper()
    hdr += [f"// {kind}: offset_min = b0 + b1*sin1 + b2*cos1 + b3*sin2 + b4*cos2  (n={len(s)})",
            f"static const float {K}_B[5] = {{{sea.intercept_:.4f}f, " +
            ", ".join(f"{c:.4f}f" for c in sea.coef_) + "};",
            f"static const float {K}_CLAMP_LO = {lo:.2f}f, {K}_CLAMP_HI = {hi:.2f}f;",
            f"static const float {K}_SAFETY_MARGIN_MIN = {m_sea:.1f}f;  // keeps violations <= {int(TARGET_VIOLATION*100)}%", ""]
meta["features"] = ASTRO + WF
meta["windows_min"] = {"dusk": [-180, -60], "dawn": [-60, 60]}
meta["target_violation_rate"] = TARGET_VIOLATION
json.dump(meta, open(MODEL_DIR / "light_model_meta.json", "w"), indent=2, default=float)

header = ["// AUTO-GENERATED by src/light/05_train_export.py - do not edit by hand",
          "// On-chip seasonal clock: offline tier of the hybrid controller.",
          f"// Site: NIIT University, Neemrana  lat={LAT} lon={LON}",
          "// Trained on May-Oct 2026 events. Outside that range the clamp keeps it sane;",
          "// retrain monthly as winter events accumulate.",
          "#pragma once", f"static const float SITE_LAT = {LAT}f, SITE_LON = {LON}f, SITE_TZ_H = 5.5f;", ""] + hdr
(ROOT / "firmware" / "light_node_hybrid" / "esp32_controller" / "seasonal_model.h").write_text("\n".join(header))
print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk != "weather_medians"} for k, v in meta.items()
                  if k in ("dusk", "dawn")}, indent=2, default=float))
print("\n".join(header))
